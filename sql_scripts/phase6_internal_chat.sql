-- 1. Create Dedicated Schema for NotifKit (Isolated from accounting tables)
CREATE SCHEMA IF NOT EXISTS notifkit;

-- 2. Enumerated Types (with idempotent IF NOT EXISTS checks)
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'chat_message_type') THEN
        CREATE TYPE chat_message_type AS ENUM ('text', 'image', 'audio', 'location');
    END IF;
    
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'chat_delivery_status') THEN
        CREATE TYPE chat_delivery_status AS ENUM ('sent', 'delivered', 'read');
    END IF;
    
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'chat_channel_type') THEN
        CREATE TYPE chat_channel_type AS ENUM ('direct', 'broadcast');
    END IF;
END $$;

-- 3. Chat Channels Table
CREATE TABLE IF NOT EXISTS chat_channels (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    channel_type chat_channel_type NOT NULL DEFAULT 'direct',
    name VARCHAR(120),                          -- Set for broadcast (e.g. 'Company Announcements')
    created_by INT REFERENCES users(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Channel Membership & Roles
CREATE TABLE IF NOT EXISTS chat_channel_members (
    channel_id UUID REFERENCES chat_channels(id) ON DELETE CASCADE,
    user_id INT REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'mgmt', 'staff')),
    last_read_message_id UUID,
    joined_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    PRIMARY KEY (channel_id, user_id)
);

-- 5. Chat Messages Table (Full Telugu UTF-8 & English support)
CREATE TABLE IF NOT EXISTS chat_messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    client_uuid VARCHAR(64) UNIQUE NOT NULL,    -- Idempotency key generated by mobile offline outbox
    channel_id UUID NOT NULL REFERENCES chat_channels(id) ON DELETE CASCADE,
    sender_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_type chat_message_type NOT NULL DEFAULT 'text',
    
    -- Content payloads
    body TEXT,                                  -- Telugu / English UTF-8 text string
    media_url TEXT,                             -- Path to compressed photo or .m4a audio file
    media_duration_sec INT,                     -- Voice note duration in seconds
    latitude NUMERIC(10, 7),                    -- GPS latitude
    longitude NUMERIC(10, 7),                   -- GPS longitude
    
    -- Delivery & WhatsApp-style Read Receipts
    status chat_delivery_status NOT NULL DEFAULT 'sent',
    delivered_at TIMESTAMP WITH TIME ZONE,
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Ensure updated_at column exists if table was already created
ALTER TABLE chat_messages ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();

-- 6. User Notification Settings (FCM & Quiet Hours for NotifKit)
CREATE TABLE IF NOT EXISTS user_notification_settings (
    user_id INT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    fcm_token TEXT,
    phone_number VARCHAR(15),
    quiet_hours_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    quiet_hours_start TIME NOT NULL DEFAULT '21:00:00',
    quiet_hours_end TIME NOT NULL DEFAULT '07:00:00',
    allow_sms_fallback BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. High-Performance B-Tree Indexes
CREATE INDEX IF NOT EXISTS idx_chat_messages_channel_created 
ON chat_messages (channel_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_chat_messages_client_uuid 
ON chat_messages (client_uuid);

CREATE INDEX IF NOT EXISTS idx_chat_messages_unread_status 
ON chat_messages (status) WHERE status != 'read';

CREATE INDEX IF NOT EXISTS idx_chat_members_user 
ON chat_channel_members (user_id);

-- 8. RBAC Trigger Function: Direct Channels must be Staff <-> Admin/Management only
-- Prohibits direct messaging between two field staff members
CREATE OR REPLACE FUNCTION check_direct_channel_rbac()
RETURNS TRIGGER AS $$
DECLARE
    curr_channel_type chat_channel_type;
    staff_count INT;
BEGIN
    SELECT channel_type INTO curr_channel_type 
    FROM chat_channels 
    WHERE id = NEW.channel_id;

    -- Only enforce check on direct 1-to-1 channels
    IF curr_channel_type = 'direct' THEN
        SELECT COUNT(*) FILTER (WHERE role = 'staff')
        INTO staff_count
        FROM chat_channel_members
        WHERE channel_id = NEW.channel_id;

        IF staff_count > 1 THEN
            RAISE EXCEPTION 'RBAC Violation: Direct channels between two field staff members are prohibited.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_check_channel_rbac ON chat_channel_members;
CREATE TRIGGER trg_check_channel_rbac
AFTER INSERT OR UPDATE ON chat_channel_members
FOR EACH ROW EXECUTE FUNCTION check_direct_channel_rbac();
